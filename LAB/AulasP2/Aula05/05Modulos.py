# Para reaproveitar funções e organizar grandes bases de código, é
# comum que queiramos separar nossos programas em arquivos
# menores.
#
# ● Em Python, podemos fazer isso por meio dos módulos.
#
# ● Um módulo é como uma biblioteca de código que podemos
# reutilizar.
#
# ● Para tanto, basta criar arquivos .py separados contendo suas
# funções, e importá-los por meio da palavra chave import.
#
# ● Ao chamar funções do módulo, deve-se colocar o nome do
# módulo na frente.

